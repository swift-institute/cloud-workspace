#!/usr/bin/env python3
"""Writes institute's ratchet table from a lint count file.

    ./ratchet.py <final-lint.json> <path to institute> [--allow-rise "<rule>" ...]

Public repositories only: private packages don't run the gate. Refuses a rise in any rule's total over the table it
replaces, unless the rule is named with --allow-rise because the rule itself changed in the same commit. A package's
limit may rise when another's falls, since folding a package moves its findings."""
import collections, json, os, re, sys

source, institute = sys.argv[1], sys.argv[2]
allowed = set(sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--allow-rise")
here = os.path.dirname(os.path.abspath(__file__))
public = {l.strip() for l in open(os.path.join(here, "repos.txt")) if l.strip()}
path = os.path.join(institute, "Sources/Institute Command/Institute.CI.Command.Source.Ratchet+limits.swift")

data = json.load(open(source))
rows = sorted((p, r, n) for p, rules in data["by_package_rule"].items() if p in public for r, n in rules.items() if n)
missing = public - set(data["by_package"])
if missing:
    sys.exit(f"not measured: {sorted(missing)[:10]}")

totals = collections.Counter()
for _, r, n in rows:
    totals[r] += n
if os.path.exists(path):
    old = collections.Counter()
    for line in open(path):
        m = re.fullmatch(r"\s*[^|\s]+\|([^|]+)\|(\d+)\n?", line)
        if m:
            old[m.group(1)] += int(m.group(2))
    rises = {r: (old[r], n) for r, n in totals.items() if n > old[r] and r not in allowed}
    if rises:
        sys.exit(f"refused, totals rise: {rises}")

body = "\n".join(f"        {p}|{r}|{n}" for p, r, n in rows)  # swift-format: 4 spaces past `static let`
open(path, "w").write(
    "import Institute_CI_Model\nimport Institute_Model\n\nextension Institute.CI.Command.Source.Ratchet {\n"
    f"    /// Generated by ratchet.py in swift-institute/cloud-workspace from a run of the runner at\n"
    f"    /// \\`{data['institute_sha']}\\`, {data['platform']}.\n".replace("\\`", "`")
    + '    static let limits = """\n' + body + '\n        """\n}\n')
print(len(rows), "limits,", sum(totals.values()), "findings,", len(public), "repositories")
